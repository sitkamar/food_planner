BEGIN;

CREATE TABLE IF NOT EXISTS public.food_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

GRANT SELECT ON TABLE public.food_sources TO service_role;

INSERT INTO public.food_sources (name) VALUES
    ('Ne'),
    ('Ano')
ON CONFLICT (name) DO NOTHING;

ALTER TABLE public.foods
    ADD COLUMN IF NOT EXISTS source_id bigint
    REFERENCES public.food_sources(id) ON DELETE SET NULL;

UPDATE public.foods AS food
SET source_id = target.id
FROM public.food_sources AS current_source
JOIN public.food_sources AS target
  ON target.name = CASE WHEN current_source.name = 'TikTok' THEN 'Ano' ELSE 'Ne' END
WHERE food.source_id = current_source.id
  AND current_source.name NOT IN ('Ano', 'Ne');

UPDATE public.foods
SET source_id = (SELECT id FROM public.food_sources WHERE name = 'Ne')
WHERE source_id IS NULL;

DELETE FROM public.food_sources
WHERE name NOT IN ('Ano', 'Ne');

DO $$
DECLARE
    no_source_id bigint;
BEGIN
    SELECT id INTO STRICT no_source_id
    FROM public.food_sources
    WHERE name = 'Ne';

    EXECUTE format('ALTER TABLE public.foods ALTER COLUMN source_id SET DEFAULT %s', no_source_id);
END;
$$;

ALTER TABLE public.foods
    ALTER COLUMN source_id SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_foods_source_id ON public.foods(source_id);

NOTIFY pgrst, 'reload schema';

COMMIT;