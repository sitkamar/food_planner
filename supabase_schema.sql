
-- Supabase SQL schema for Food Planner
-- Generated from database.csv

CREATE TABLE IF NOT EXISTS food_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS food_supercategories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_type_id bigint NOT NULL REFERENCES food_types(id) ON DELETE RESTRICT,
    name text NOT NULL,
    UNIQUE (food_type_id, name)
);

CREATE TABLE IF NOT EXISTS food_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supercategory_id bigint NOT NULL REFERENCES food_supercategories(id) ON DELETE CASCADE,
    name text NOT NULL,
    UNIQUE (supercategory_id, name)
);

CREATE TABLE IF NOT EXISTS food_subcategories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES food_categories(id) ON DELETE CASCADE,
    name text NOT NULL,
    UNIQUE (category_id, name)
);

CREATE TABLE IF NOT EXISTS foods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    supercategory_id bigint NOT NULL REFERENCES food_supercategories(id) ON DELETE CASCADE,
    category_id bigint NOT NULL REFERENCES food_categories(id) ON DELETE CASCADE,
    subcategory_id bigint REFERENCES food_subcategories(id) ON DELETE SET NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (supercategory_id, category_id, subcategory_id, name)
);

CREATE TABLE IF NOT EXISTS weekly_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_start_date date NOT NULL UNIQUE,
    title text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weekly_plan_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekly_plan_id bigint NOT NULL REFERENCES weekly_plans(id) ON DELETE CASCADE,
    slot_group text NOT NULL CHECK (slot_group IN ('breakfast', 'main', 'snack', 'non_cooking')),
    slot_index integer NOT NULL CHECK (slot_index >= 1),
    food_id bigint NOT NULL REFERENCES foods(id) ON DELETE RESTRICT,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (weekly_plan_id, slot_group, slot_index)
);

CREATE TABLE IF NOT EXISTS freezer_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_id bigint REFERENCES foods(id) ON DELETE SET NULL,
    name text NOT NULL,
    quantity numeric(10,2) NOT NULL DEFAULT 0,
    unit text NOT NULL DEFAULT 'porce',
    added_at date NOT NULL DEFAULT CURRENT_DATE,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stock_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    quantity numeric(10,2) NOT NULL DEFAULT 0,
    unit text NOT NULL DEFAULT 'kg',
    category text,
    expires_at date,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_food_supercategories_type ON food_supercategories(food_type_id);
CREATE INDEX IF NOT EXISTS idx_foods_supercategory ON foods(supercategory_id);
CREATE INDEX IF NOT EXISTS idx_foods_category ON foods(category_id);
CREATE INDEX IF NOT EXISTS idx_foods_subcategory ON foods(subcategory_id);
CREATE INDEX IF NOT EXISTS idx_weekly_plans_week_start_date ON weekly_plans(week_start_date);
CREATE INDEX IF NOT EXISTS idx_freezer_items_name ON freezer_items(name);
CREATE INDEX IF NOT EXISTS idx_stock_items_name ON stock_items(name);
CREATE INDEX IF NOT EXISTS idx_stock_items_expires_at ON stock_items(expires_at);

